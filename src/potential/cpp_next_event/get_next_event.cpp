double get_final_position_of_non_tunnel_event(double position, int movement_direction, std::vector<double> roots){
    std::sort(roots.begin(), roots.end());

    if(position < 0.0){
        if(movement_direction > 0){
            return roots.at(1);
        }
        else{
            return roots.at(0);
        }
    }
    else{
        if(movement_direction > 0){
            return roots.at(3);
        }
        else{
            return roots.at(2);
        }
    }
}


bool check_all_roots_real(std::vector<std::complex<double>> roots){
    bool real_roots = true;
    for(int i = 0; i < 4; i++){
        std::complex<double> ith_root = roots.at(i); // dereferencing roots_ptr to access the value of array roots_ptr[i]
        if(ith_root.imag() != 0.0){
            real_roots = false;
        }
    }
    return real_roots;
}

std::vector<std::complex<double>>  get_harmonic_potential_roots(double mass, double timestep, double omega_squared, double final_action){
  
    std::array<std::complex<double>, 2> roots; 
    double a = 0.5 * mass * timestep * omega_squared;
    double b = 0.0;
    double c = -final_action;

    roots = get_quadratic_roots(a, b, c);
    std::vector<std::complex<double>> roots_vect(roots.begin(), roots.end());

    return roots_vect;
}

std::vector<std::complex<double>> get_anharmonic_potential_roots(double mass, double timestep, double anharmonicity,
                      double omega_squared, double final_action){
    std::array<std::complex<double>, 2> roots_ptr; 
    std::array<std::complex<double>, 4> roots; 
    double a = timestep * anharmonicity;
    double b = 0.5 * mass * timestep * omega_squared;
    double c = -final_action;

    roots_ptr = get_quadratic_roots(a, b, c);

    roots.at(0) = sqrt(roots_ptr.at(0)); 
    roots.at(1) = -sqrt(roots_ptr.at(0));
    roots.at(2) = sqrt(roots_ptr.at(1)); 
    roots.at(3) = -sqrt(roots_ptr.at(1));

    std::vector<std::complex<double>> roots_vect(roots.begin(), roots.end());

    return roots_vect;
  
}


std::array<std::complex<double>, 2> get_quadratic_roots(double a, double b, double c){
    // complex type because we could sqrt a -ve number here
    std::array<std::complex<double>, 2> roots; 

    roots.at(0) = (-b + std::sqrt(std::complex<double>(pow(b, 2) - 4 * a * c))) / (2 * a);
    roots.at(1) = (-b - std::sqrt(std::complex<double>(pow(b, 2) - 4 * a * c))) / (2 * a);

    return roots;
}


double get_final_position_of_single_well_event(int movement_direction, std::array<double, 2> roots){
    if ((movement_direction > 0) && (roots.at(0) > roots.at(1))){
        return roots.at(0);
    }
    else if ((movement_direction > 0) && (roots.at(0) < roots.at(1))){
        return roots.at(1);
    }
    else if ((movement_direction < 0) && (roots.at(0) < roots.at(1))){
        return roots.at(0);
    }
    else{
        return roots.at(1);
    }
}

double get_final_position_of_single_well_event(int movement_direction, std::vector<double> roots){
    if(roots.size() == 2){
    if ((movement_direction > 0) && (roots.at(0) > roots.at(1))){
        return roots.at(0);
    }
    else if ((movement_direction > 0) && (roots.at(0) < roots.at(1))){
        return roots.at(1);
    }
    else if ((movement_direction < 0) && (roots.at(0) < roots.at(1))){
        return roots.at(0);
    }
    else{
        return roots.at(1);
    }
    }
    else{
    throw std::invalid_argument("Invalid argument to double get_final_position_of_single_well_event(int movement_direction, std::vector<double> roots), \n std::vector<double> roots should have length 2");
    }
}

int get_east_worldline_neighbour(int lattice_site_index, int number_of_quantum_particles, int number_of_timeslices){
    return (lattice_site_index + number_of_quantum_particles) %
              (number_of_timeslices * number_of_quantum_particles);
}

int get_west_worldline_neighbour(int lattice_site_index, int number_of_quantum_particles, int number_of_timeslices){
    return (lattice_site_index - number_of_quantum_particles) %
            (number_of_timeslices * number_of_quantum_particles);
}

